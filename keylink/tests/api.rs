//! Where the actor surface is spelled from, now that most of it is generated.
//!
//! This file used to assert that thirteen names re-exported out of `actor`
//! resolved **unparameterized** — `let _: System = ..` — because a downstream
//! crate wrote them that way and a type-parameter default was what made it
//! possible. That premise is gone rather than reduced. An actor system is
//! per-service: `M` is the service's own mailbox type, the defaults that stood
//! in for it are deleted, and the names a caller writes are generated aliases in
//! the service's own module.
//!
//! So the claim this file makes now is:
//!
//! 1. **Three names still resolve bare**, because they never had a parameter:
//!    `Eviction`, `MountError` and `mount`. Not eight, not thirteen.
//! 2. **The generated module supplies the rest** — `System`, `SystemBuilder`,
//!    `Mounted`, `Mailbox`, `Mail`, `KeyedClient`, `ActorRef` — fully applied,
//!    in type position and in expression position wherever each admits one.
//! 3. **The keylink-level generics need a parameter**, and the one that used to
//!    be rescued by a default in expression position — `DEFAULT_CAPACITY` — is
//!    reached through the alias instead.
//! 4. **The serving side's idempotency policy resolves from out here** —
//!    `Keyable`, `Records`, `ServiceBuilder::keyable`, `ServiceBuilder::records`
//!    and `IdempotencyRefusal::NotKeyable`.
//!    Not part of the actor surface, and here for the reason in the paragraph
//!    below: this is the only consumer-position file in the repo, and `rpc.rs`
//!    deliberately reaches `Keyable` through `crate::idempotency` so that the root
//!    re-export has exactly one guard rather than none.
//!
//! The pairing of the two positions is still the point rather than pedantry:
//! `SystemBuilder::DEFAULT_CAPACITY` stopped compiling once while
//! `let _: SystemBuilder = ..` went on compiling, because a type-parameter
//! default applies in type position and not in expression position. There are no
//! defaults left to be caught out by, and the pairing is what would notice one
//! coming back.
//!
//! This is still the only place in the repo these names are written from a
//! consumer's position. Everything in-crate reaches them through `super::` or
//! `crate::`, which resolves whether or not the re-export survives, and
//! `cargo clippy -p keylink --lib` cannot see any of it — the code that meets
//! these names is generated by `macros.rs` and expands in the *caller's* crate.
//!
//! There is nothing to assert at run time. This test passing means it compiled,
//! which is the entire claim.

#![allow(clippy::expect_used, clippy::unwrap_used)]

use keylink::{
    mount, ActorId, Allowlist, Body, BodyReader, Caller, Ended, Eviction, Keyable, KeyedService,
    MountError, Origin, Records, Reply,
};

keylink::service! {
    service Depot;

    rpc Count() -> u64;
    rpc Note(line: String) -> u64;
}

/// The exact signature `KeyedService::mail` has to keep, factored out because
/// the annotation below is the assertion and `clippy::type_complexity` refuses
/// it inline. A `type` is what that lint asks for, and it costs nothing here:
/// every one of the six types is still written down in one place, which is what
/// makes a change to any of them a red test in this file.
type MailConstructor =
    fn(Origin, depot::Request, BodyReader, Reply<(depot::Response, Body)>) -> depot::Mail;

struct Counter(u64);

impl depot::Actor for Counter {
    async fn count(&mut self, _cx: Caller<'_>) -> u64 {
        self.0
    }

    async fn note(&mut self, _cx: Caller<'_>, _line: String) -> u64 {
        self.0 += 1;
        self.0
    }
}

#[tokio::test]
async fn the_three_unparameterized_names_still_resolve_bare() {
    // ── type position ────────────────────────────────────────────────────────
    // `mount` is a function and admits none.
    let _: Eviction = Eviction::Never;
    let _: Option<MountError> = None;

    // ── expression position ──────────────────────────────────────────────────
    let _ = Eviction::Never;
    let _ = MountError::AtCapacity {
        capacity: depot::SystemBuilder::DEFAULT_CAPACITY,
    };
    // `M` is a *function* generic and function generics cannot carry defaults,
    // so it is inferred — and the only thing here to infer it from is the
    // closure's annotation. That was true before the per-service rewrite and it
    // is unchanged by it: drop the `: depot::Mailbox` and this is `E0282`.
    let _ = mount(|mut inbox: depot::Mailbox| async move {
        while inbox.recv().await.is_some() {}
        Ended::Stopped
    });
}

/// Made red by `scripts/break-once.sh`, replacing the generated
/// `pub type SystemBuilder = $crate::SystemBuilder<Mail>;` with
/// `pub type SystemBuilder<M> = $crate::SystemBuilder<M>;` — an alias that passes
/// the parameter on instead of applying it, which is the shape this whole file
/// exists to refuse. Watched: this does not run, it does not compile —
/// `error[E0107]` at the type-position line here, "add missing generic argument",
/// plus `E0282` where the expression-position use loses its inference. A compile
/// error is the only red a compile-only test has.
#[tokio::test]
async fn the_generated_module_supplies_the_rest_fully_applied() {
    // ── type position ────────────────────────────────────────────────────────
    let _: depot::SystemBuilder = depot::System::builder(Eviction::Never);
    let system: depot::System = depot::System::builder(Eviction::Never).build();
    let _: depot::Mounted = depot::spawn(Counter(0));
    let _: Option<depot::Mail> = None;
    let _: Option<depot::KeyedClient> = None;
    // The type `with_idempotency` hands back. Written from a consumer's
    // position because that is the only place it can be: a caller names it to
    // hold one in a struct or to return one, and until this line nothing
    // outside `macros.rs` named it at all.
    let _: Option<depot::IdempotentClient> = None;
    let _: Option<depot::blocking::IdempotentClient> = None;

    // ── expression position ──────────────────────────────────────────────────
    // `Mail`, `Mailbox` and `Mounted` admit none: an alias, and two types a
    // consumer never constructs by name.
    let _ = depot::keyed_alpn();
    let _ = depot::alpn();
    let _ = depot::SystemBuilder::DEFAULT_CAPACITY;
    let _ = depot::KeyedClient::close;
    // Annotated, because `impl Into<Idempotency>` makes the function item
    // generic and a bare path is `E0283`. The annotation is the assertion: it
    // names the type `with_idempotency` returns, which is the whole finding.
    let _: fn(&depot::Client, keylink::IdempotencyKey) -> depot::IdempotentClient =
        depot::Client::with_idempotency;
    let _ = depot::IdempotentClient::close;
    let _ = depot::at;
    let _ = depot::keyed_service(&system, Allowlist::anyone());

    assert!(system.is_empty());
}

/// **The serving side's idempotency policy, written from a consumer's position.**
///
/// This file's header scopes it to the actor surface, and these names are not part
/// of that. They are here anyway for the reason the header gives: this is the
/// only place in the repo that writes keylink's own names the way a downstream crate
/// writes them, and a policy a caller cannot reach from outside is a policy that
/// does not exist. `keyable` in particular is reached through a `ServiceBuilder` the
/// *generated* module hands back, so the annotation pins that the builder method
/// survives the erasure `service()` performs.
///
/// The pairing of the two positions is the same discipline as the test above.
///
/// Made red by `scripts/break-once.sh` replacing
/// `Idempotency, IdempotencyRefusal, KeyState, Keyable, MAX_ATTACH` in
/// `keylink/src/lib.rs` with the same line minus ` Keyable,`. Watched: this does not
/// run, it does not compile —
///
/// ```text
/// error[E0432]: unresolved import `keylink::Keyable`
///   --> keylink/tests/api.rs   # at this file's own `use`
/// error: could not compile `keylink` (test "api") due to 1 previous error
/// ```
///
/// A compile error is the only red a compile-only test has.
///
/// **That break was watched twice, and the first run is the reason `rpc.rs` imports
/// `Keyable` from `crate::idempotency`.** With `rpc.rs` reaching for
/// `crate::Keyable`, the same edit failed inside the library's own import and it never
/// compiled, so this test could not run and therefore guarded nothing about the
/// re-export. Moving that one import is what turned a vacuous guard into this
/// output. `tests/idempotency.rs` now names `keylink::Keyable` too and would fail
/// the same way; this is the file whose purpose is the name.
///
/// The half that has no other guard anywhere is `ServiceBuilder::keyable` as a
/// function item. Made red by `scripts/break-once.sh` replacing
/// `pub fn keyable(mut self, keyable: Keyable) -> Self {` with
/// `pub fn keyed(mut self, keyable: Keyable) -> Self {`. Watched:
///
/// ```text
/// error[E0599]: no associated function or constant named `keyable` found for
///   struct `ServiceBuilder<Req, Resp>` in the current scope
///   --> keylink/tests/api.rs   # at the annotation below
/// ```
///
/// The library itself still compiled under that edit — nothing in-crate calls the
/// method — which is what makes this annotation the only thing holding the name.
///
/// `ServiceBuilder::records` is the same story and was watched the same way, by
/// replacing `pub fn records(mut self, records: Records) -> Self {` with
/// `pub fn recording(mut self, records: Records) -> Self {`: `error[E0599]: no
/// associated function or constant named `records` found for struct
/// `ServiceBuilder<Req, Resp>` in the current scope`, and `error: could not compile
/// `keylink` (test "api") due to 1 previous error` — the library again untouched.
#[tokio::test]
async fn the_serving_side_key_policy_resolves_from_outside() {
    // ── type position ────────────────────────────────────────────────────────
    let _: Keyable = Keyable::Any;
    let _: Option<Keyable> = None;
    let _: Records = Records::Memory;
    let _: Option<Records> = None;

    // ── expression position ──────────────────────────────────────────────────
    let _ = Keyable::Only(&["Count"]);
    let _ = Keyable::Except(&["Note"]);
    let _ = Keyable::None;
    // The whole point of the export: a policy set on the builder a *generated*
    // module returns. Annotated, because that is the assertion — the method has to
    // be reachable on the erased-schema builder, not on some private type.
    let _: fn(
        keylink::ServiceBuilder<depot::Request, depot::Response>,
        Keyable,
    ) -> keylink::ServiceBuilder<depot::Request, depot::Response> =
        keylink::ServiceBuilder::keyable;
    let _ = Records::None;
    let _: fn(
        keylink::ServiceBuilder<depot::Request, depot::Response>,
        Records,
    ) -> keylink::ServiceBuilder<depot::Request, depot::Response> =
        keylink::ServiceBuilder::records;
    // And the refusal a caller has to be able to match on, since it is what a
    // refused key arrives as.
    let _ = keylink::IdempotencyRefusal::NotKeyable {
        method: "Count".to_owned(),
    };
}

/// The names only generated code is meant to write, written by hand once so
/// that a change to any of their signatures is a red test here rather than a
/// break in somebody's expansion.
///
/// All four are `#[doc(hidden)] pub` — hidden from the docs, not from the
/// compiler, and therefore a compatibility promise whatever the attribute says.
#[tokio::test]
async fn the_hidden_seam_the_macro_writes_is_reachable_and_typed() {
    // `Addressed<T>` has private fields and exactly two doors, `new` and
    // `split`. `Rpc` is what a layer reads it through.
    let addressed = keylink::Addressed::new(
        ActorId::new("obra/4471").expect("valid"),
        depot::Request::Note {
            line: "muda de ipê".to_owned(),
        },
    );
    assert_eq!(keylink::Rpc::method(&addressed), "Note");
    assert_eq!(
        keylink::Rpc::actor(&addressed).map(ActorId::as_str),
        Some("obra/4471")
    );
    let (id, _message) = addressed.split();
    assert_eq!(id.as_str(), "obra/4471");

    // `KeyedService` is what carries a generated service's three types across
    // the crate boundary, and `Reply<T>` is the reply channel its `mail`
    // constructor takes. Named as a function item rather than called: a
    // `BodyReader` is a QUIC stream's receiving half and has no public
    // constructor, and `Reply` has no public constructor either — keylink builds
    // every reply channel — which is the correct shape. `mail` is implemented out
    // here and called only by keylink, from a place that already holds both.
    //
    // The annotation is the assertion. Every one of the six types in it is part
    // of the seam, so a change to any of them is a red test here rather than a
    // break inside somebody's expansion. `Reply<(Response, Body)>` and not
    // `Reply<Response>`: a `recv` reply and its body travel together off the
    // actor's task, and the pair is what the loop answers with.
    let _: MailConstructor = <depot::Actors as KeyedService>::mail;

    // And `Origin` hands out a BORROWED `Caller`, which is the whole reason the
    // mailbox carries an owned origin instead of a `Caller<'static>` nobody can
    // build (RFC-07 §1.6). Named as a function item, because out here there is no
    // way to get an `Origin`: the field is private and both constructors are
    // `pub(crate)`, so keylink hands one *in* to a generated loop and a downstream
    // crate can never build a second one around a `Context` it already delivered.
    //
    // The annotation is the assertion twice over. It pins that `caller` is
    // reachable from out here at all — a private one is `E0624` at the one site
    // that must call it — and that the lifetime relates the borrow to the origin,
    // so `for<'a> fn(&'a Origin) -> Caller<'a>` is what a turn gets and `'static`
    // is not on offer.
    let _: fn(&Origin) -> Caller<'_> = Origin::caller;
}
