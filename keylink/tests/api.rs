//! The thirteen names `lib.rs` re-exports out of `actor`, spelled from outside.
//!
//! These are the names a downstream crate writes, and this file is the only
//! place in the repo they are written from a consumer's position. Everything
//! in-crate reaches them through `super::` or `crate::`, which resolves whether
//! or not the re-export survives, and every in-crate test already has a type
//! parameter in hand. So a module that moves, or a generic parameter that loses
//! its default, breaks nobody here and everybody downstream — and `cargo clippy
//! -p keylink --lib` cannot see it either, because the code that meets these
//! names is generated by `macros.rs` and expands in the *caller's* crate.
//!
//! Each name appears **unparameterized**, in type position and in expression
//! position, wherever it admits one. The pairing is the point rather than
//! pedantry: `SystemBuilder::DEFAULT_CAPACITY` stopped compiling while
//! `let _: SystemBuilder = ..` went on compiling, because a type-parameter
//! default applies in type position and not in expression position. Five of the
//! thirteen admit only one position and are marked below.
//!
//! There is nothing to assert at run time. This test passing means it compiled,
//! which is the entire claim; an assertion underneath it would say less than the
//! build already said.

#![allow(clippy::expect_used, clippy::unwrap_used)]

use keylink::{
    actor_schema, mount, ActorClient, ActorId, ActorReply, ActorRequest, Eviction, Mail, Mailbox,
    MountError, Mounted, Sealed, System, SystemBuilder,
};

#[tokio::test]
async fn every_re_exported_name_resolves_without_a_parameter() {
    // ── type position ────────────────────────────────────────────────────────
    // `actor_schema` and `mount` are functions and admit none.
    let _: Eviction = Eviction::Never;
    let _: Option<ActorClient> = None;
    let _: Option<ActorReply> = None;
    let _: Option<ActorRequest> = None;
    let _: Option<Mail> = None;
    let _: Option<MountError> = None;
    let _: Option<Sealed> = None;
    let _: SystemBuilder = System::builder(Eviction::Never);
    let _: System = System::builder(Eviction::Never).build();
    let _: Mounted = mount(1, |mut inbox: Mailbox| async move {
        while inbox.recv().await.is_some() {}
    });

    // ── expression position ──────────────────────────────────────────────────
    // `Mail`, `Mailbox` and `Mounted` admit none: an alias, and two types a
    // consumer never constructs by name.
    let _ = Eviction::Never;
    let _ = MountError::AtCapacity {
        capacity: SystemBuilder::DEFAULT_CAPACITY,
    };
    let _ = System::alpn();
    let _ = ActorClient::close;
    let _ = Sealed::open::<u8>;
    let _ = actor_schema::<u8>("keylink/api");
    let _ = ActorReply::encode(&9u8);
    let _ = ActorRequest::new(ActorId::new("probe").expect("valid"), 7, &9u8);
    // The one name whose default does not carry on its own. `mount`'s `M` is a
    // *function* generic, and function generics cannot have defaults — so `M` is
    // inferred, and the only thing here to infer it from is `Mailbox`, whose own
    // default supplies `Mail`. Drop the `: Mailbox` annotation and this stops
    // compiling with `E0282`, where before the parameterization it did not.
    //
    // Written out because the file above claims each name resolves
    // unparameterized, and for this one that is true only with an annotation the
    // generated code always happens to supply. A downstream caller writing
    // `mount` by hand has to know that, and `mount` being `#[doc(hidden)]` is the
    // reason this is a footnote rather than a break worth declaring.
    let _ = mount(1, |mut inbox: Mailbox| async move {
        while inbox.recv().await.is_some() {}
    });
}
